#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::settings::find;

    #[test]
    fn registry_has_one_entry_per_setting_and_they_are_unique() {
        assert_eq!(REGISTRY.len(), 44);
        for def in REGISTRY {
            assert_eq!(find(def.key).map(|d| d.key), Some(def.key));
        }
    }
}
